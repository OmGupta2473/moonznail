import type { NextConfig } from "next";

const supabaseHost = (() => {
  try {
    return new URL(process.env.NEXT_PUBLIC_SUPABASE_URL ?? "").hostname;
  } catch {
    return null;
  }
})();

const nextConfig: NextConfig = {
  /* config options here */
  reactCompiler: true,
  turbopack: {
    rules: {
      "*.css": {
        loaders: ["@tailwindcss/turbopack"],
        as: "*.css",
      },
    },
  },
  images: {
    // Allows the image optimizer to fetch from Supabase when the host resolves
    // to a private IP (some networks intercept DNS). Safe here because the only
    // URLs passed to the optimizer are constructed from NEXT_PUBLIC_SUPABASE_URL
    // and validated storage paths — no user input.
    dangerouslyAllowLocalIP: true,
    remotePatterns: supabaseHost
      ? [{ protocol: "https", hostname: supabaseHost, pathname: "/storage/v1/object/public/**" }]
      : [],
  },
};

export default nextConfig;